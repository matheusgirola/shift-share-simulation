"""
ssa_dgp.py
==========
Artificial data-generating process (DGP) for testing shift-share models.

Design philosophy
-----------------
Shift-share analysis (SSA) claims to decompose regional growth into a
national effect, an industry-mix effect, and a regional/competitive effect.
To test which SSA variant best *recovers* these effects, we build the data
so that the three effects exist BY CONSTRUCTION, with known values.

The growth rate of employment in region r, industry i, year t is:

    g[r,i,t] = n[t]  +  m[i,t]  +  c[r,i]  +  eps[r,i,t]

where
    n[t]     : national growth rate in year t                (NATIONAL effect)
    m[i,t]   : industry deviation from national rate         (INDUSTRY-MIX effect)
               m[i,t] = m_bar[i] + small yearly wobble, employment-weighted mean ~ 0
    c[r,i]   : region-industry competitive rate              (COMPETITIVE effect)
               c[r,i] = c_bar[r] + d[r,i]
               c_bar[r] : common regional advantage (mean 0 across regions)
               d[r,i]   : region-industry interaction (mean 0 within region)
    eps      : iid noise, N(0, sigma_eps) -- unrecoverable by any model

Employment evolves multiplicatively:  E[r,i,t+1] = E[r,i,t] * (1 + g[r,i,t])

Because growth is applied one year at a time, the *exact* additive truth in
employment units along the realized path is:

    Delta E[r] = SUM_{i,t} E[r,i,t]*n[t]           (TRUE national component)
               + SUM_{i,t} E[r,i,t]*m[i,t]         (TRUE industry-mix component)
               + SUM_{i,t} E[r,i,t]*c[r,i]         (TRUE competitive component)
               + SUM_{i,t} E[r,i,t]*eps[r,i,t]     (noise component)

This identity holds to machine precision, so every model can be scored
against an unambiguous ground truth.

Allocation structure (for Esteban-Marquillas testing)
-----------------------------------------------------
Regions are assigned to three groups:
  * "well_allocated"  : initial industry shares tilted TOWARD industries
                        where the region has d[r,i] > 0  -> true allocation
                        effect should be positive.
  * "mis_allocated"   : shares tilted AWAY from advantaged industries
                        -> true allocation effect should be negative.
  * "neutral"         : shares drawn independently of d[r,i].

The TRUE allocation component is computed along the path as
    SUM_{i,t} (E[r,i,t] - E*[r,i,t]) * c[r,i]
where E*[r,i,t] is homothetic employment (region total x national industry
share) -- i.e., exactly the object the E-M allocation effect targets.

Spatial structure (for Nazara-Hewings testing)
----------------------------------------------
Regions are the 27 Brazilian states (see brazil_geo.py). With rho_space > 0
the common regional advantage is generated by a spatial autoregressive (SAR)
process on the row-standardized contiguity matrix W:

    c_bar = (I - rho_space * W)^{-1} u ,   u ~ N(0, sd_region)

so a state's competitive rate is correlated with its neighbors'. The truth
then also records the Nazara-Hewings split of the competitive component:

    true_neigh[r]   = SUM_{i,t} E[r,i,t] * (W c)[r,i]   neighborhood effect
    true_own_net[r] = SUM_{i,t} E[r,i,t] * (c - Wc)[r,i] own-vs-neighbors
    (true_neigh + true_own_net == true_comp exactly)

Dataset dimensions: 27 states (Brazilian UFs), 5 sectors, 10 growth years
(11 annual employment observations, t = 0..10).
"""

import numpy as np
import pandas as pd

from brazil_geo import UFS, contiguity_matrix

REGIONS = UFS  # 27 Brazilian states
SECTORS = ["Agro", "Industry", "Construction", "Commerce", "Services"]
N_YEARS = 10  # growth periods


def generate_dataset(
    seed=42,
    n_regions=27,
    n_sectors=5,
    n_years=10,
    mean_national=0.025,
    sd_national=0.012,
    sd_mix=0.020,
    sd_mix_wobble=0.004,
    sd_region=0.015,
    sd_interaction=0.010,
    sd_eps=0.006,
    allocation_tilt=6.0,
    rho_space=0.0,
):
    """Return dict with employment panel, true parameters, true components.

    rho_space in [0, 1): spatial autocorrelation of the regional competitive
    effect on the Brazilian contiguity matrix (0 = no spatial structure,
    reproducing the original a-spatial experiment).
    """
    rng = np.random.default_rng(seed)
    R, I, T = n_regions, n_sectors, n_years
    regions = REGIONS[:R]
    sectors = SECTORS[:I] if I <= len(SECTORS) else [f"S{k}" for k in range(I)]
    W = contiguity_matrix(row_standardize=True)[:R, :R]
    if R < 27:  # re-standardize if trimmed
        W = W / np.maximum(W.sum(axis=1, keepdims=True), 1e-12)

    # ---- 1. True parameters (rate space) --------------------------------
    n_t = rng.normal(mean_national, sd_national, size=T)  # national rate per year

    m_bar = rng.normal(0.0, sd_mix, size=I)
    m_bar -= m_bar.mean()  # center
    m_it = m_bar[:, None] + rng.normal(0, sd_mix_wobble, (I, T))  # industry x year
    m_it -= m_it.mean(axis=0, keepdims=True)  # mean-zero each year

    # spatially autocorrelated regional advantage: SAR process on W
    u = rng.normal(0.0, sd_region, size=R)
    if rho_space != 0.0:
        c_bar = np.linalg.solve(np.eye(R) - rho_space * W, u)
        c_bar *= sd_region / c_bar.std()  # keep scale comparable
    else:
        c_bar = u
    c_bar -= c_bar.mean()
    d_ri = rng.normal(0.0, sd_interaction, size=(R, I))
    d_ri -= d_ri.mean(axis=1, keepdims=True)  # mean-zero within region
    c_ri = c_bar[:, None] + d_ri  # region x industry competitive rate

    # ---- 2. Region groups & initial employment (allocation structure) ---
    groups = np.array(["neutral"] * R, dtype=object)
    idx = rng.permutation(R)
    groups[idx[: R // 3]] = "well_allocated"
    groups[idx[R // 3 : 2 * R // 3]] = "mis_allocated"

    region_size = rng.lognormal(mean=12.0, sigma=0.8, size=R)  # heterogeneous sizes
    base_conc = np.full(I, 8.0)  # Dirichlet baseline
    E0 = np.zeros((R, I))
    for r in range(R):
        tilt = np.zeros(I)
        if groups[r] == "well_allocated":
            tilt = allocation_tilt * (d_ri[r] / (np.abs(d_ri[r]).max() + 1e-12))
        elif groups[r] == "mis_allocated":
            tilt = -allocation_tilt * (d_ri[r] / (np.abs(d_ri[r]).max() + 1e-12))
        alpha = np.clip(base_conc + tilt, 0.5, None)
        shares = rng.dirichlet(alpha)
        E0[r] = region_size[r] * shares

    # ---- 3. Simulate employment path ------------------------------------
    E = np.zeros((R, I, T + 1))
    E[:, :, 0] = E0
    eps = rng.normal(0.0, sd_eps, size=(R, I, T))
    g = np.zeros((R, I, T))
    for t in range(T):
        g[:, :, t] = n_t[t] + m_it[:, t][None, :] + c_ri + eps[:, :, t]
        E[:, :, t + 1] = E[:, :, t] * (1.0 + g[:, :, t])

    # ---- 4. Exact true components in employment units (along path) ------
    Ew = E[:, :, :T]  # weights: employment at start of each year
    true_nat = (Ew * n_t[None, None, :]).sum(axis=(1, 2))  # (R,)
    true_mix = (Ew * m_it.T[None, :, :].transpose(0, 2, 1)).sum(axis=(1, 2))  # (R,)
    true_comp = (Ew * c_ri[:, :, None]).sum(axis=(1, 2))  # (R,)
    true_noise = (Ew * eps).sum(axis=(1, 2))  # (R,)
    # sanity: identity holds exactly
    assert np.allclose(
        E[:, :, T].sum(1) - E[:, :, 0].sum(1),
        true_nat + true_mix + true_comp + true_noise,
    )

    # homothetic employment along the path -> true allocation component
    reg_tot = E.sum(axis=1)  # (R, T+1)
    nat_shares = E.sum(axis=0) / E.sum(axis=(0, 1))  # (I, T+1)
    E_star = reg_tot[:, None, :] * nat_shares[None, :, :]  # (R, I, T+1)
    true_alloc = ((Ew - E_star[:, :, :T]) * c_ri[:, :, None]).sum(axis=(1, 2))
    true_comp_homothetic = (E_star[:, :, :T] * c_ri[:, :, None]).sum(axis=(1, 2))

    # Arcelus II truth: c_ri = c_bar + d_ri by construction, so the region-
    # wide advantage and the within-region, sector-specific deviation are the
    # exact counterparts of the regional and differential shifts
    true_reg_shift = (Ew * c_bar[:, None, None]).sum(axis=(1, 2))
    true_diff_shift = (Ew * d_ri[:, :, None]).sum(axis=(1, 2))
    assert np.allclose(true_reg_shift + true_diff_shift, true_comp)

    # Nazara-Hewings truth: split competitive rate into the neighborhood
    # average (W c) and the own-vs-neighborhood remainder (c - W c)
    Wc = W @ c_ri  # (R, I)
    true_neigh = (Ew * Wc[:, :, None]).sum(axis=(1, 2))
    true_own_net = (Ew * (c_ri - Wc)[:, :, None]).sum(axis=(1, 2))
    assert np.allclose(true_neigh + true_own_net, true_comp)

    # ---- 5. Tidy panel for the models -----------------------------------
    rows = []
    for r, reg in enumerate(regions):
        for i, sec in enumerate(sectors):
            for t in range(T + 1):
                rows.append((reg, sec, t, E[r, i, t]))
    panel = pd.DataFrame(rows, columns=["region", "sector", "year", "employment"])

    truth = pd.DataFrame(
        {
            "region": regions,
            "group": groups,
            "c_bar": c_bar,  # true avg regional competitive RATE
            "true_national": true_nat,  # employment-unit components
            "true_mix": true_mix,
            "true_comp": true_comp,
            "true_comp_homothetic": true_comp_homothetic,
            "true_alloc": true_alloc,
            "true_reg_shift": true_reg_shift,
            "true_diff_shift": true_diff_shift,
            "true_neigh": true_neigh,
            "true_own_net": true_own_net,
            "true_noise": true_noise,
            "delta_E": E[:, :, T].sum(1) - E[:, :, 0].sum(1),
        }
    )

    return {
        "panel": panel,
        "truth": truth,
        "E": E,
        "regions": regions,
        "sectors": sectors,
        "W": W,
        "n_t": n_t,
        "m_it": m_it,
        "c_ri": c_ri,
        "c_bar": c_bar,
        "d_ri": d_ri,
        "eps": eps,
        "groups": groups,
        "n_years": T,
        "rho_space": rho_space,
    }


if __name__ == "__main__":
    data = generate_dataset()
    print(data["panel"].head())
    print("\nTrue components (first 5 regions):")
    print(data["truth"].head().round(1))
    tot = data["truth"][["true_national", "true_mix", "true_comp", "true_noise"]].sum(
        axis=1
    )
    print(
        "\nIdentity check (max abs error):",
        np.abs(tot - data["truth"]["delta_E"]).max(),
    )
